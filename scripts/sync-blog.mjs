import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.resolve(root,'..','블로그콘텐츠');
const posts=[];
for(const entry of await fs.readdir(source,{withFileTypes:true})){
  if(!entry.isDirectory()||!/^\d{4}-\d{2}-\d{2}_/.test(entry.name))continue;
  const folder=path.join(source,entry.name);
  const meta=JSON.parse((await fs.readFile(path.join(folder,'게시정보.json'),'utf8')).replace(/^\uFEFF/,''));
  if(!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(meta.slug))throw new Error('Invalid blog slug');
  let body=(await fs.readFile(path.join(folder,'게시글.md'),'utf8')).replace(/^# [^\r\n]+\r?\n\s*/,'').trim();
  body=body.replace(/^\*([^*]+)\*$/gm,'$1');
  const imageName=meta.slug+'.png';
  await fs.copyFile(path.join(folder,'대표이미지.png'),path.join(root,'assets','images',imageName));
  posts.push({id:'bundled-'+meta.slug,slug:meta.slug,title:meta.title,excerpt:meta.summary,body,category:'보도자료',author:'대한바른자세걷기협회',source_name:meta.source_name,source_url:meta.source_url,cover_id:'',cover_image:'/assets/images/'+imageName,cover_alt:meta.image_alt,cover_caption:meta.image_caption,asset_ids:'[]',status:'published',published_at:meta.date+'T09:00:00+09:00',updated_at:meta.date+'T09:00:00+09:00'});
}
if(new Set(posts.map(p=>p.slug)).size!==posts.length)throw new Error('Duplicate blog slug');
await fs.writeFile(path.join(root,'server','bundled-posts.mjs'),'// Generated by scripts/sync-blog.mjs from date-based blog folders.\nexport const bundledPosts = '+JSON.stringify(posts,null,2)+';\n');
console.log(`Synced ${posts.length} blog posts with images.`);
